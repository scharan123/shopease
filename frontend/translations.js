window.currentLang = localStorage.getItem('shopease_lang') || 'en';

function applyTranslation(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const text = node.nodeValue.trim();
    if (text) {
      if (node._origText === undefined) {
        const isKnown = Object.keys(translations.en).includes(text);
        if (isKnown) node._origText = text;
      }
      const origText = node._origText;
      if (origText) {
        const tr = translations[window.currentLang] && translations[window.currentLang][origText];
        if (tr) {
          node.nodeValue = node.nodeValue.replace(text, tr);
        } else if (window.currentLang === 'en') {
          node.nodeValue = node.nodeValue.replace(text, origText);
        }
      }
    }
  } else if (node.nodeType === Node.ELEMENT_NODE) {
    if (node.tagName === 'SCRIPT' || node.tagName === 'STYLE') return;
    if (node.placeholder) {
      if (!node.dataset.origPlaceholder) node.dataset.origPlaceholder = node.placeholder;
      const orig = node.dataset.origPlaceholder;
      const tr = translations[window.currentLang] && translations[window.currentLang][orig];
      node.placeholder = tr ? tr : (window.currentLang === 'en' ? orig : node.placeholder);
    }
    node.childNodes.forEach(child => applyTranslation(child));
  }
}

function updateLanguage(lang) {
  window.currentLang = lang;
  localStorage.setItem('shopease_lang', lang);
  applyTranslation(document.body);
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('btn-primary', btn.dataset.lang === lang);
    btn.classList.toggle('btn-secondary', btn.dataset.lang !== lang);
  });
}

function initLanguageSelector() {
  const languages = [
    { code: 'en', label: 'English' },
    { code: 'te', label: 'తెలుగు (Telugu)' },
    { code: 'kn', label: 'ಕನ್ನಡ (Kannada)' },
    { code: 'hi', label: 'हिन्दी (Hindi)' },
    { code: 'ta', label: 'தமிழ் (Tamil)' },
    { code: 'ml', label: 'മലയാളം (Malayalam)' }
  ];

  const optsContainer = document.getElementById('language-options');
  if (optsContainer) {
    optsContainer.innerHTML = languages.map(l => 
      `<button type="button" class="btn ${window.currentLang === l.code ? 'btn-primary' : 'btn-secondary'} lang-btn" data-lang="${l.code}" style="text-align:left; justify-content:flex-start; width:100%;">${l.label}</button>`
    ).join('');
  }

  const modal = document.getElementById('language-modal');
  const backdrop = document.getElementById('language-modal-backdrop');

  document.body.addEventListener('click', (e) => {
    const langItem = e.target.closest('#language-item, #mobile-language-item, #settings-language-btn');
    if (langItem) {
      modal.style.display = 'flex';
      backdrop.style.display = 'block';
      const pd = document.getElementById('profile-dropdown');
      if (pd) pd.style.display = 'none';
      const mpd = document.getElementById('mobile-profile-dropdown');
      if (mpd) mpd.style.display = 'none';
    }

    const langBtn = e.target.closest('.lang-btn');
    if (langBtn) {
      updateLanguage(langBtn.dataset.lang);
      modal.style.display = 'none';
      backdrop.style.display = 'none';
    }

    if (e.target.closest('#language-modal-close') || e.target === backdrop) {
      modal.style.display = 'none';
      backdrop.style.display = 'none';
    }
  });

  setTimeout(() => applyTranslation(document.body), 100);

  const observer = new MutationObserver((mutations) => {
    if (mutations.some(m => m.addedNodes.length > 0)) {
      observer.disconnect();
      applyTranslation(document.body);
      observer.observe(document.body, { childList: true, subtree: true });
    }
  });
  observer.observe(document.body, { childList: true, subtree: true });
}

document.addEventListener('DOMContentLoaded', initLanguageSelector);
